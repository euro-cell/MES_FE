// ── Helpers ───────────────────────────────────────────────────────────────────

function stdevP(arr: number[]): number {
  if (arr.length === 0) return 0;
  const mean = arr.reduce((a, b) => a + b, 0) / arr.length;
  return Math.sqrt(arr.reduce((s, x) => s + (x - mean) ** 2, 0) / arr.length);
}

function calcStats(rows: WeightInspectionRow[]) {
  const weights    = rows.map(r => r.weight).filter((v): v is number => v !== null);
  const thicknesses = rows.map(r => r.thickness).filter((v): v is number => v !== null);
  const avg  = (arr: number[]) => arr.length ? arr.reduce((a, b) => a + b, 0) / arr.length : null;
  const max  = (arr: number[]) => arr.length ? Math.max(...arr) : null;
  const min  = (arr: number[]) => arr.length ? Math.min(...arr) : null;
  return {
    avg:   { weight: avg(weights),    thickness: avg(thicknesses) },
    max:   { weight: max(weights),    thickness: max(thicknesses) },
    min:   { weight: min(weights),    thickness: min(thicknesses) },
    stdev: { weight: stdevP(weights), thickness: stdevP(thicknesses) },
  };
}

/**
 * 엑셀 FREQUENCY 방식: (prev, current] 상한값 기준
 * 확률밀도: NORM.DIST(x, mean, stdev, false) × pdfWidth
 * → pdfWidth: 무게=2(계급폭), 두께=0.5(엑셀 /(1/0.5) 방식)
 * → 전체 데이터 기준으로 계산 (엑셀 C9:C383 버그 수정)
 */
function buildDistribution(
  values: number[],
  start: number,
  step: number,
  count: number,
  mean: number,
  stdev: number,
  pdfWidth?: number,
): DistributionBin[] {
  const width = pdfWidth ?? step;
  const bins: DistributionBin[] = [];
  for (let i = 0; i < count; i++) {
    const classValue = parseFloat((start + i * step).toFixed(10));
    const prev = i === 0 ? -Infinity : parseFloat((start + (i - 1) * step).toFixed(10));
    const freq = values.filter(v => v > prev && v <= classValue).length;
    const pdf = stdev > 0
      ? (1 / (stdev * Math.sqrt(2 * Math.PI))) * Math.exp(-0.5 * ((classValue - mean) / stdev) ** 2) * width
      : 0;
    bins.push({ classValue, frequency: freq, probabilityDensity: pdf });
  }
  return bins;
}

function isOutOfSpec(value: number | null, spec: SpecValue | undefined): boolean {
  if (value === null || !spec) return false;
  const min = spec.min ?? (spec.target !== undefined && spec.tolerance !== undefined ? spec.target - spec.tolerance : undefined);
  const max = spec.max ?? (spec.target !== undefined && spec.tolerance !== undefined ? spec.target + spec.tolerance : undefined);
  if (min !== undefined && value < min) return true;
  if (max !== undefined && value > max) return true;
  return false;
}

function specLabel(s: SpecValue | undefined): string {
  if (!s || s.target === undefined) return '미설정';
  if (s.tolerance !== undefined) return `${s.target}±${s.tolerance}`;
  return `${s.target}`;
}

